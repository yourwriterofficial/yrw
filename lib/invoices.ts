import type { SupabaseClient } from '@supabase/supabase-js';

/** Strip the bracketed service tag (e.g. "[DEV] ", "[PROPOSAL] ") from an order topic. */
export function cleanTopic(topic: string): string {
  return (topic || '').replace(/^\[[^\]]+\]\s*/g, '').trim();
}

interface OrderLike {
  order_id: string;
  legal_name?: string | null;
  guest_name?: string | null;
  email?: string | null;
  guest_email?: string | null;
  client_phone?: string | null;
  whatsapp_sync?: string | null;
  guest_whatsapp?: string | null;
  client_company?: string | null;
  client_address?: string | null;
  topic: string;
  additional_info?: string | null;
  financial_quote?: number | null;
  payment_milestones?: any[] | null;
  sixty_percent_paid?: boolean | null;
  forty_percent_paid?: boolean | null;
  payment_structure_type?: string | null;
}

export interface InvoiceDefaults {
  contact_email: string;
  bank_name: string;
  account_name: string;
  account_number: string;
  developer_signature_name: string;
  default_terms: string[];
  default_deliverables: any[];
  default_additional_services: string[];
  default_exclusions: string[];
  default_timeline: any[];
}

